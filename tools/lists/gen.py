import sys

sys.path.insert(0, os.path.dirname(__file__))
import i18n_keys  # noqa: E402
import registry  # noqa: E402

EN = i18n_keys.load('en')
AR = i18n_keys.load('ar')
SYSTEM = "'00000000-0000-4000-8000-000000000000'"


def sql(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def java(text: str) -> str:
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def codes_of(entry):
    found = []
    for prefix in entry['prefixes']:
        for code in i18n_keys.codes(EN, prefix):
            if code not in found:
                found.append(code)
    if 'codes' in entry:
        missing = [c for c in entry['codes'] if c not in found]
        assert not missing, (entry['code'], 'codes without a message', missing)
        return list(entry['codes'])
    return found


def label(messages, entry, code):
    for prefix in entry['prefixes']:
        key = prefix + code
        if key in messages:
            return messages[key], key
    raise AssertionError((entry['code'], code))


problems = []
rows = []  # (list, code, ar, en, sort, system)
for entry in registry.LISTS:
    codes = codes_of(entry)
    assert codes, entry['code']
    entry['resolved'] = codes
    for index, code in enumerate(codes, 1):
        ar, arkey = label(AR, entry, code)
        en, enkey = label(EN, entry, code)
        for prefix in entry['prefixes']:
            if prefix + code in EN and EN[prefix + code] != en:
                problems.append(f"{entry['code']}.{code}: '{prefix}' says '{EN[prefix + code]}', seeded '{en}'")
        if not entry.get('seeded'):
            rows.append((entry['code'], code, ar, en, index, entry['cls'] == 'b'))

