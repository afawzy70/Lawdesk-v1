#!/usr/bin/env python3
"""LawDesk repository policy checks (LD-001).

Usage:
  repo_policy.py branch <name>
  repo_policy.py commit-msg <file>
  repo_policy.py pr <head-branch> <base-branch>
  repo_policy.py layout [repo-root]

Exit codes: 0 compliant, 1 policy violation (details on stderr), 2 usage error.
The rules are documented in CONTRIBUTING.md; keep both in sync.
"""

import re
import sys
from pathlib import Path

LONG_LIVED_BRANCHES = ("main", "develop")
WORK_PREFIXES = ("feature", "fix", "docs", "qa", "chore")
MAIN_PREFIXES = ("release", "hotfix")

_BRANCH_RE = re.compile(r"^(?P<prefix>[a-z]+)/(?P<slug>[A-Za-z0-9][A-Za-z0-9._-]*)$")
_COMMIT_TYPES = ("feat", "fix", "docs", "test", "refactor", "chore", "ci", "build", "perf", "style", "revert")
_COMMIT_RE = re.compile(r"^(?:%s)(?:\([A-Za-z0-9._-]+\))?!?: \S.*$" % "|".join(_COMMIT_TYPES))
# Subjects generated by git or GitHub rather than written by people.
_EXEMPT_SUBJECT_RE = re.compile(r'^(Merge (pull request|branch|remote-tracking branch) |Revert "|Initial commit$)')
MAX_SUBJECT_LENGTH = 72

REQUIRED_PATHS = (
    "README.md",
    "CONTRIBUTING.md",
    ".editorconfig",
    ".gitattributes",
    ".gitignore",
    ".github/CODEOWNERS",
    ".github/pull_request_template.md",
    "docs/delivery/PHASE-1-CHECKPOINT.md",
)


def check_branch_name(name):
    if name in LONG_LIVED_BRANCHES:
        return []
    match = _BRANCH_RE.match(name)
    allowed = ", ".join(p + "/" for p in WORK_PREFIXES + MAIN_PREFIXES)
    if not match or ".." in name:
        return [f"branch '{name}' must look like <prefix>/<slug> with prefix one of {allowed} "
                "and a slug of letters, digits, '.', '_' or '-' (e.g. feature/LD-002-backend-bootstrap)"]
    if match.group("prefix") not in WORK_PREFIXES + MAIN_PREFIXES:
        return [f"branch '{name}' has unknown prefix '{match.group('prefix')}/'; use one of {allowed}"]
    return []


def check_commit_message(message):
    lines = [line for line in message.splitlines() if not line.startswith("#")]
    subject = next((line.strip() for line in lines if line.strip()), "")
    if not subject:
        return ["commit message is empty"]
    if _EXEMPT_SUBJECT_RE.match(subject):
        return []
    errors = []
    if not _COMMIT_RE.match(subject):
        errors.append(f"commit subject '{subject}' must follow 'type(scope): summary' with type one of "
                      f"{', '.join(_COMMIT_TYPES)}; put the story ID in the scope, e.g. 'feat(LD-002): add health endpoint'")
    if len(subject) > MAX_SUBJECT_LENGTH:
        errors.append(f"commit subject is {len(subject)} characters; keep it within {MAX_SUBJECT_LENGTH}")
    return errors


def check_pull_request(head, base):
    errors = check_branch_name(head)
    prefix = head.split("/", 1)[0]
    if base == "develop":
        # Work branches and back-merges of main are fine; release/hotfix branches go to main.
        if prefix in MAIN_PREFIXES or head == "develop":
            errors.append(f"'{head}' may not target develop; release/* and hotfix/* branches target main")
    elif base == "main":
        if prefix not in MAIN_PREFIXES:
            errors.append(f"'{head}' may not target main; open the pull request against develop "
                          "(only release/* and hotfix/* branches merge into main)")
    else:
        errors.append(f"pull requests must target develop or main, not '{base}'")
    return errors


def check_layout(root):
    root = Path(root)
    return [f"required file missing: {path}" for path in REQUIRED_PATHS if not (root / path).is_file()]


def main(argv):
    commands = {
        "branch": (1, lambda a: check_branch_name(a[0])),
        "commit-msg": (1, lambda a: check_commit_message(Path(a[0]).read_text(encoding="utf-8"))),
        "pr": (2, lambda a: check_pull_request(a[0], a[1])),
        "layout": (None, lambda a: check_layout(a[0] if a else Path(__file__).resolve().parents[1])),
    }
    if not argv or argv[0] not in commands:
        print(__doc__, file=sys.stderr)
        return 2
    arity, check = commands[argv[0]]
    args = argv[1:]
    if (arity is not None and len(args) != arity) or (arity is None and len(args) > 1):
        print(__doc__, file=sys.stderr)
        return 2
    errors = check(args)
    for error in errors:
        print(f"policy: {error}", file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
